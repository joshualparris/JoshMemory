#!/usr/bin/env python3
"""Generate STATUS.md: a short, token-cheap summary of where this repo is up to.

Reads the existing task registers (no IDs or statuses are changed), recent
commits and open pull requests, and writes a short handover a fresh agent can
read instead of the large CSVs. Handoffs and claims are private, so this links
to them rather than copying them. A workflow regenerates it daily and whenever
a register changes.
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import subprocess
import sys
from pathlib import Path
from urllib import request

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / "STATUS.md"

DONE = {"DONE", "COMPLETE", "COMPLETED", "VERIFIED", "VERIFIED_COMPLETE", "TRIAGED_DOCS", "TASKS_COMMITTED"}
NEXT_ELIGIBLE = {"OPEN", "NOT_TRIAGED", "SOURCE_REPORTED_OPEN"}

# (label, path, id column, status column, order column or None, action column or None)
REGISTERS = [
    ("Portfolio triage (repositories)", "docs/PORTFOLIO_TRIAGE_REGISTRY_2026-10-24.csv", "queue", "triage_status", None, "repository"),
    ("Portfolio triage steps", "docs/PORTFOLIO_TRIAGE_TASK_STEPS_2026-10-25.csv", "step_id", "state", None, "work_item"),
    ("Execution queue", "docs/MASTER_20_AGENT_EXECUTION_QUEUE_2026-10-25.csv", "task_id", "status", "execution_rank", "action"),
    ("Values alignment tasks", "docs/VALUES_ALIGNMENT_TASKS_2026-11-14.csv", "task_id", "status", None, "action"),
    ("Whole-repo task register (source-reported, unverified)", "docs/JOSHMEMORY_OPEN_TASK_REGISTER.csv", "task_id", "state", None, None),
]
NEXT_QUEUE_LIMIT = 5
REPO = "joshualparris/JoshMemory"
PURPOSE = (
    "Evidence-aware continuity for AI coding agents across Josh's projects: shared handoffs, "
    "project facts, work claims and the portfolio task registers."
)


def recent_commits(limit: int = 5) -> list[str]:
    try:
        out = subprocess.run(
            ["git", "log", f"-{limit}", "--format=%h|%cs|%s"], cwd=ROOT, capture_output=True, text=True, check=True
        ).stdout
    except (OSError, subprocess.CalledProcessError):
        return []
    rows = []
    for line in out.splitlines():
        sha, date, subject = (line.split("|", 2) + ["", ""])[:3]
        rows.append(f"- `{sha}` {date}: {_short(subject, 100)}")
    return rows


def open_pull_requests() -> list[dict] | None:
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "joshmemory-status"}
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = request.Request(f"https://api.github.com/repos/{REPO}/pulls?state=open&per_page=100", headers=headers)
    try:
        with request.urlopen(req, timeout=15) as response:
            return json.loads(response.read().decode("utf-8"))
    except Exception:
        return None


def _pr_lines(prs: list[dict] | None) -> list[str]:
    if prs is None:
        return ["Unknown: GitHub could not be reached when this was built. Check open PRs before starting."]
    bots = [pr for pr in prs if str(pr.get("user", {}).get("login", "")).endswith("[bot]")]
    people = sorted((pr for pr in prs if pr not in bots), key=lambda pr: pr["number"])
    lines = [f"- #{pr['number']}: {_short(pr.get('title') or '', 90)}" for pr in people]
    if bots:
        lines.append(f"- plus {len(bots)} dependency-update PRs from bots")
    return lines or ["None."]


def _category(status: str) -> str:
    value = status.strip().upper()
    if value in DONE:
        return "done"
    if "BLOCKED" in value or "DEVICE_REQUIRED" in value:
        return "blocked"
    return "open"


def _rows(path: str) -> list[dict[str, str]]:
    with open(ROOT / path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def _short(text: str, limit: int = 90) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def build(commits: list[str] | None = None, prs: list[dict] | None = None) -> str:
    commits = recent_commits() if commits is None else commits
    built_from = commits[0].split("`")[1] if commits else "unknown"
    lines = [
        "# Status",
        "",
        "<!-- Generated by tools/build_status.py. Do not edit by hand; run `python tools/build_status.py`. -->",
        "",
        f"Read this first. Built from commit `{built_from}`; anything newer is in the commit log. **Purpose:** {PURPOSE}",
        "",
        "## Before you start",
        "",
        "1. Read [AGENTS.md](AGENTS.md).",
        "2. Read the latest handover and active claims for your project: authorised agents follow the [agent handoff guide](docs/AGENT_HANDOFF.md) to the private repository's README, which links a one-section-per-project handover index. If you cannot reach it, treat both as unknown.",
        "3. Compare that handover with the recent commits and open PRs below. Do not redo finished work.",
        "4. When you finish: set the task's status in its register (this file then updates itself) and save a handoff with what changed, the proof, the uncertainty and the next unclaimed action.",
        "",
        "## Recently landed",
        "",
        *(commits or ["Unknown: no git history available when this was built."]),
        "",
        "## Open pull requests",
        "",
        *_pr_lines(prs),
        "",
        "## Task progress",
        "",
        "| Register | Done | Open | Blocked | Total | Next open |",
        "|---|---:|---:|---:|---:|---|",
    ]
    queue_next: list[str] = []
    for label, path, id_col, status_col, order_col, action_col in REGISTERS:
        rows = _rows(path)
        if order_col:
            rows.sort(key=lambda row: int(row[order_col] or 0))
        counts = {"done": 0, "open": 0, "blocked": 0}
        next_id = ""
        for row in rows:
            status = row[status_col]
            counts[_category(status)] += 1
            if not next_id and status.strip().upper() in NEXT_ELIGIBLE:
                next_id = row[id_col]
                if action_col and label.startswith("Portfolio triage (repo"):
                    next_id = f"{next_id} ({row[action_col]})"
            if order_col and len(queue_next) < NEXT_QUEUE_LIMIT and status.strip().upper() in NEXT_ELIGIBLE:
                queue_next.append(f"{len(queue_next) + 1}. `{row[id_col]}`: {_short(row[action_col])}")
        link = f"[{label}]({path})"
        lines.append(
            f"| {link} | {counts['done']:,} | {counts['open']:,} | {counts['blocked']:,} | {len(rows):,} | {next_id or '—'} |"
        )
    lines += [
        "",
        "Done means a verified or completed status in the register. Everything else not blocked counts as open, including tasks marked triaged at parent level but not verified step by step.",
        "",
        "## Next open tasks",
        "",
        "Portfolio triage: the next repository is shown in the table above. Execution queue, in order:",
        "",
        *queue_next,
        "",
        "Before starting one, check active claims and current repo evidence: the register may lag behind recent work.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Exit 1 if STATUS.md is out of date")
    args = parser.parse_args(argv)
    content = build(prs=open_pull_requests())
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print("STATUS.md is out of date; run: python tools/build_status.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

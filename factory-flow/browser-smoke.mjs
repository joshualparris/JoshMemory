import assert from 'node:assert/strict';
import { chromium } from 'playwright';
const target=process.env.FACTORY_URL||'http://127.0.0.1:8732/';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1500,height:900}});
const errors=[];
page.on('pageerror',err=>errors.push(err.message));
try{
 const response=await page.goto(target,{waitUntil:'domcontentloaded',timeout:45000});
 assert.equal(response?.status(),200,'Game must return 200');
 await page.waitForSelector('#board .tile');
 assert.equal(await page.locator('#board .tile').count(),228,'19x12 board must render');
 assert.equal(await page.locator('#tools .tool').count(),8,'Eight build tools should be present');
 assert.match(await page.locator('#contractTitle').innerText(),/First Light/);
 if(await page.locator('#guide').evaluate(el=>el.open))await page.locator('#startPlaying').click();
 assert.equal(await page.locator('#credits').innerText(),'$440');
 const slot=page.locator('[data-x="8"][data-y="8"]');
 await slot.click();
 assert.match(await page.locator('[data-x="8"][data-y="8"]').getAttribute('class'),/belt/,'Click should build a conveyor');
 await page.locator('[data-x="8"][data-y="8"]').click({button:'right'});
 assert.equal(await page.locator('[data-x="8"][data-y="8"] .arrow').innerText(),'↓','Right-click must rotate the existing conveyor');
 await page.locator('#undoButton').click();
 assert.equal(await page.locator('[data-x="8"][data-y="8"] .arrow').innerText(),'→','Undo should restore original direction');
 await page.locator('#undoButton').click();
 assert.doesNotMatch(await page.locator('[data-x="8"][data-y="8"]').getAttribute('class'),/belt/,'Undo should remove the building');
 await page.locator('[data-x="8"][data-y="8"]').click();
 const creditBefore=await page.locator('#credits').innerText();
 await page.reload({waitUntil:'domcontentloaded'});
 await page.waitForSelector('#board .tile');
 assert.match(await page.locator('[data-x="8"][data-y="8"]').getAttribute('class'),/belt/,'Local save should restore after reload');
 assert.equal(await page.locator('#credits').innerText(),creditBefore,'Credits should persist after reload');
 await page.locator('#speedButton').click();
 assert.match(await page.locator('#speedButton').innerText(),/2×/,'Speed control should work');
 await page.locator('#pauseButton').click();
 assert.match(await page.locator('#pauseButton').innerText(),/Resume/,'Pause control should work');
 await page.locator('#helpButton').click();
 assert.equal(await page.locator('#guide').evaluate(el=>el.open),true);
 await page.locator('#closeGuide').click();
 assert.deepEqual(errors,[],'Browser should have no uncaught page errors');
 console.log('PASS: browser loads '+target+'; 228 tiles; building, rotation, undo, save reload, speed, pause and tutorial work.');
}finally{await browser.close();}

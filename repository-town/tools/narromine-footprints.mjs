// Real building footprints for Narromine from Microsoft Global ML Building Footprints (ODbL 1.0,
// © Microsoft; release 2026-02-03, quadkey 311230010). Each footprint is traced from aerial/satellite
// imagery; height is Microsoft's ML estimate (metres, -1/0 when unknown). We keep outlines inside the
// Narromine OSM export bbox, fit each to its minimum-area rotated rectangle (the shape the game
// draws), and write src/world/narromine-footprints-data.js.
//   node tools/narromine-footprints.mjs <tile.csv.gz>
import fs from 'node:fs'; import zlib from 'node:zlib';
import { geoToWorld } from '../src/world/narromine-layout.js';
import { NARROMINE_OSM } from '../src/world/narromine-osm-data.js';
const bb = NARROMINE_OSM.bbox, lines = zlib.gunzipSync(fs.readFileSync(process.argv[2])).toString().trim().split('\n');
const out = [];
for (const line of lines) {
  const f = JSON.parse(line), ring = f.geometry.coordinates[0];
  const lon = ring.reduce((s, p) => s + p[0], 0) / ring.length, lat = ring.reduce((s, p) => s + p[1], 0) / ring.length;
  if (lon < bb.minlon || lon > bb.maxlon || lat < bb.minlat || lat > bb.maxlat) continue;
  const pts = ring.slice(0, -1).map(([lo, la]) => geoToWorld(la, lo));
  let best = null;                                // minimum-area rectangle over the outline's edge directions
  for (let i = 0; i < pts.length; i++) {
    const [ax, az] = pts[i], [bx, bz] = pts[(i + 1) % pts.length], a = Math.atan2(bz - az, bx - ax), c = Math.cos(a), s = Math.sin(a);
    let u0 = Infinity, u1 = -Infinity, v0 = Infinity, v1 = -Infinity;
    for (const [x, z] of pts) { const u = x * c + z * s, v = -x * s + z * c; u0 = Math.min(u0, u); u1 = Math.max(u1, u); v0 = Math.min(v0, v); v1 = Math.max(v1, v); }
    const area = (u1 - u0) * (v1 - v0);
    if (!best || area < best.area) { const um = (u0 + u1) / 2, vm = (v0 + v1) / 2; best = { area, w: u1 - u0, d: v1 - v0, a, x: um * c - vm * s, z: um * s + vm * c }; }
  }
  if (best.area < 8) continue;                    // drop specks (< 8 m²), not buildings
  const h = f.properties?.height > 1.5 ? Math.round(f.properties.height * 10) / 10 : 0;
  out.push([best.x, best.z, best.w, best.d, -best.a, h].map((v, i) => i === 4 ? Math.round(v * 1000) / 1000 : i === 5 ? v : Math.round(v * 10) / 10));
}
fs.writeFileSync('src/world/narromine-footprints-data.js',
  '// Generated by tools/narromine-footprints.mjs — do not edit.\n' +
  '// Source: Microsoft Global ML Building Footprints, release 2026-02-03, quadkey 311230010 (ODbL 1.0, © Microsoft).\n' +
  '// Each entry: [x, z, width, depth, yaw, heightEstimateMetres(0 = unknown)] in game world metres.\n' +
  'export const NARROMINE_FOOTPRINTS = ' + JSON.stringify(out) + ';\n');
console.log('footprints', out.length);

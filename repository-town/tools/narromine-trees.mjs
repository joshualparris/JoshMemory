// Converts LiDAR-detected trees (tools/narromine_trees.py output) to game positions and writes
// src/world/narromine-trees-data.js. Drops detections whose trunk would stand on a mapped road or
// track, or inside a building outline (canopy over a roof or road is kept as real overhang).
//   node tools/narromine-trees.mjs trees.json
import fs from 'node:fs';
import { planDandalooStreetscape } from '../src/world/narromine-dandaloo-streetscape-data.js';
import { geoToWorld, STREETS, RAIL, BUILDINGS, FILL_HOUSES, DETAILED, inPoly, REGION } from '../src/world/narromine-layout.js';
const raw = JSON.parse(fs.readFileSync(process.argv[2]));
const segs = [...STREETS.map(s => [s, (s.width || 7) / 2 + 0.8]), ...RAIL.map(r => [r, 2.2])];
const near = (x, z) => segs.some(([s, m]) => s.pts.some((b, i) => { if (!i) return false; const a = s.pts[i - 1], dx = b[0] - a[0], dz = b[1] - a[1], l = dx * dx + dz * dz || 1;
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / l)); return Math.hypot(x - a[0] - t * dx, z - a[1] - t * dz) < m; }));
const placed = planDandalooStreetscape(STREETS).trees;   // photo-placed Dandaloo Street trees: don't double them
// Detailed landmark sites (hotel, post office, church...) and a 3 m band around them: verandah and
// awning roofs there can read as canopy peaks, and their footpaths must stay walkable.
const nearDetailed = (x, z) => DETAILED.some(d => inPoly(x, z, d.boundary) || d.boundary.some((b, i) => { const a = d.boundary[(i + d.boundary.length - 1) % d.boundary.length], dx = b[0] - a[0], dz = b[1] - a[1], l = dx * dx + dz * dz || 1;
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / l)); return Math.hypot(x - a[0] - t * dx, z - a[1] - t * dz) < 3; }));
// Owner's Street View/Mapillary comparison (4 Nov 2026): no trees stand in front of the Narromine Hotel;
// its rear-yard trees come from the hotel builder. Keep LiDAR detections out of a 40 m band around it.
const HOTEL = DETAILED.find(d => d.id === 'narromine-hotel');
const nearHotel = (x, z) => HOTEL && (inPoly(x, z, HOTEL.boundary) || HOTEL.boundary.some((b, i) => { const a = HOTEL.boundary[(i + HOTEL.boundary.length - 1) % HOTEL.boundary.length], dx = b[0] - a[0], dz = b[1] - a[1], l = dx * dx + dz * dz || 1;
  const t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / l)); return Math.hypot(x - a[0] - t * dx, z - a[1] - t * dz) < 40; }));
const out = [];
for (const [lat, lon, h, r] of raw) {
  const [x, z] = geoToWorld(lat, lon);
  if (x < REGION.x0 || x > REGION.x1 || z < REGION.z0 || z > REGION.z1) continue;
  if (nearHotel(x, z) || nearDetailed(x, z) || placed.some(t => Math.hypot(t.x - x, t.z - z) < 6) || near(x, z) || BUILDINGS.some(b => inPoly(x, z, b.pts)) || FILL_HOUSES.some(f => Math.abs(f.x - x) < 25 && Math.abs(f.z - z) < 25 && inPoly(x, z, f.rect.poly))) continue;
  out.push([Math.round(x * 10) / 10, Math.round(z * 10) / 10, h, Math.min(r, 9)]);
}
// Clean-up of the raw peaks: a crown narrower than 1.8 m on a tall stem is a pole, light or sign, not a
// tree; and peaks within 3 m (or 60% of the larger crown) of a taller one are the same tree.
const kept = [];
for (const t of out.filter(t => t[3] >= 1.8).sort((a, b) => b[2] - a[2]))
  if (!kept.some(k => Math.hypot(k[0] - t[0], k[1] - t[1]) < Math.max(3, 0.6 * Math.max(k[3], t[3])))) kept.push(t);
out.length = 0; out.push(...kept);
fs.writeFileSync('src/world/narromine-trees-data.js', '// Generated by tools/narromine-trees.mjs from tools/narromine_trees.py — do not edit.\n' +
  '// Trees detected in NSW Spatial Services MacquarieFloodplainSouth 2023 airborne LiDAR (CC BY 4.0, (c) State of\n' +
  '// New South Wales, Spatial Services), tiles 6166432/6166433. Each: [x, z, height m, crown radius m].\n' +
  'export const NARROMINE_TREES = ' + JSON.stringify(out) + ';\n');
const hs = out.map(t => t[2]).sort((a, b) => a - b);
console.log('kept', out.length, 'of', raw.length, 'height p10/p50/p90', [0.1, 0.5, 0.9].map(q => hs[Math.floor(q * hs.length)]));

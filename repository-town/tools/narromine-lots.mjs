#!/usr/bin/env node
// Converts NSW Spatial Services cadastre "Lot" GeoJSON (NSW_Cadastre MapServer layer 9, WGS84)
// into src/world/narromine-lots-data.js: simplified lot outlines in the game's local map metres.
// Usage: node tools/narromine-lots.mjs lots-1.geojson [lots-2.geojson ...]
// Re-run it to regenerate the data. Only lot number and plan label are kept (public cadastre
// identifiers); owners, areas and every other attribute are dropped.
// Source: © State of New South Wales (NSW Spatial Services), CC BY 4.0.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { NARROMINE_OSM as OSM } from '../src/world/narromine-osm-data.js';

const here = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(here, '..', 'src', 'world', 'narromine-lots-data.js');
const TOLERANCE_M = 0.3;       // Douglas–Peucker tolerance
const MIN_AREA_M2 = 1;         // drop slivers
const MARGIN_M = 40;           // same margin the layout REGION uses around the OSM extent

// Same projection as geoToWorld in narromine-layout.js, minus the world OFFSET (data stays in map metres).
const RAD = Math.PI / 180, EARTH = 6371008.8, COS = Math.cos(OSM.anchor.lat * RAD);
const toLocal = ([lon, lat]) => [(lon - OSM.anchor.lon) * RAD * EARTH * COS, -(lat - OSM.anchor.lat) * RAD * EARTH];

const distToSeg = (p, a, b) => {
  const dx = b[0] - a[0], dz = b[1] - a[1], l2 = dx * dx + dz * dz;
  const t = l2 ? Math.max(0, Math.min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dz) / l2)) : 0;
  return Math.hypot(p[0] - (a[0] + t * dx), p[1] - (a[1] + t * dz));
};
function dp(pts, tol) {        // open polyline, endpoints kept
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [i, j] = stack.pop(); let max = 0, at = -1;
    for (let k = i + 1; k < j; k++) { const d = distToSeg(pts[k], pts[i], pts[j]); if (d > max) { max = d; at = k; } }
    if (max > tol) { keep[at] = 1; stack.push([i, at], [at, j]); }
  }
  return pts.filter((_, k) => keep[k]);
}
function simplifyRing(ring, tol) {   // closed ring: split at the farthest vertex so it cannot collapse
  let far = 1, best = 0;
  for (let k = 1; k < ring.length; k++) { const d = Math.hypot(ring[k][0] - ring[0][0], ring[k][1] - ring[0][1]); if (d > best) { best = d; far = k; } }
  const a = dp(ring.slice(0, far + 1), tol), b = dp([...ring.slice(far), ring[0]], tol);
  return [...a.slice(0, -1), ...b.slice(0, -1)];
}
const area = (r) => Math.abs(r.reduce((s, p, i) => { const q = r[(i + 1) % r.length]; return s + p[0] * q[1] - q[0] * p[1]; }, 0)) / 2;

const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node tools/narromine-lots.mjs lots-1.geojson [...]'); process.exit(1); }
const E = OSM.extent, box = { x0: E.x0 - MARGIN_M, x1: E.x1 + MARGIN_M, z0: E.z0 - MARGIN_M, z1: E.z1 + MARGIN_M };
const seen = new Set(); const lots = []; let read = 0, outside = 0, thin = 0, dup = 0;
for (const f of files) {
  for (const ft of JSON.parse(fs.readFileSync(f, 'utf8')).features) {
    read++;
    const id = ft.properties.objectid; if (seen.has(id)) { dup++; continue; } seen.add(id);
    const polys = ft.geometry.type === 'Polygon' ? [ft.geometry.coordinates] : ft.geometry.coordinates;
    const lot = String(ft.properties.lotnumber ?? ''), plan = String(ft.properties.planlabel ?? '');
    let any = false;
    for (const poly of polys) {                      // outer ring of each part; holes are not drawn
      let ring = poly[0].map(toLocal);
      if (ring.length > 1 && ring[0][0] === ring[ring.length - 1][0] && ring[0][1] === ring[ring.length - 1][1]) ring.pop();
      if (ring.length < 3) continue;
      const xs = ring.map((p) => p[0]), zs = ring.map((p) => p[1]);
      if (Math.max(...xs) < box.x0 || Math.min(...xs) > box.x1 || Math.max(...zs) < box.z0 || Math.min(...zs) > box.z1) { outside++; continue; }
      ring = simplifyRing(ring, TOLERANCE_M);
      if (ring.length < 3 || area(ring) < MIN_AREA_M2) { thin++; continue; }
      const d = ring.map(([x, z]) => [Math.round(x * 10), Math.round(z * 10)]);   // decimetres
      const flat = [d[0][0], d[0][1]]; for (let i = 1; i < d.length; i++) flat.push(d[i][0] - d[i - 1][0], d[i][1] - d[i - 1][1]);
      lots.push([lot, plan, flat]); any = true;
    }
  }
}
lots.sort((p, q) => p[1].localeCompare(q[1]) || p[0].localeCompare(q[0], undefined, { numeric: true }));
const meta = { source: 'NSW Spatial Services cadastre, Lot layer (NSW_Cadastre MapServer 9)', licence: 'CC BY 4.0', attribution: '© State of New South Wales (NSW Spatial Services)',
  exported: new Date().toISOString().slice(0, 10), units: 'rings: [lot, plan, [x0, z0, dx1, dz1, ...]] in decimetres of local map metres (x east, z south), as narromine-osm-data.js' };
fs.writeFileSync(OUT, `// Generated by tools/narromine-lots.mjs from NSW cadastre lots — do not edit by hand.\n// © State of New South Wales (NSW Spatial Services), CC BY 4.0. Lot number and plan label only.\nexport const NARROMINE_LOTS = ${JSON.stringify({ ...meta, lots })};\n`);
const vertices = lots.reduce((s, l) => s + l[2].length / 2, 0);
console.log(`lots read ${read}, rings kept ${lots.length}, outside ${outside}, too thin ${thin}, duplicates ${dup}, vertices ${vertices}, wrote ${path.relative(process.cwd(), OUT)} (${(fs.statSync(OUT).size / 1024).toFixed(0)} KB)`);

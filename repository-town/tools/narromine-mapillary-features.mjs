// Street objects detected by Mapillary across Narromine (map_features API; positions triangulated from
// CC BY-SA 4.0 street-level photos) -> src/world/narromine-mapillary-data.js. Keeps signs, crossings,
// stop lines and street furniture; drops give-way signs already mapped in OSM (within 12 m).
//   node tools/narromine-mapillary-features.mjs feats.jsonl
import fs from 'node:fs';
import { geoToWorld, REGION, STREETS } from '../src/world/narromine-layout.js';
import { NARROMINE_FURNITURE } from '../src/world/narromine-furniture-data.js';
const KEEP = [
  [/^regulatory--maximum-speed-limit-(\d+)/, m => ['speed', +m[1]]], [/^regulatory--end-of-maximum-speed-limit-(\d+)/, m => ['speedEnd', +m[1]]],
  [/^regulatory--stop--/, () => ['stop']], [/^regulatory--yield--/, () => ['giveway']], [/^regulatory--keep-left/, () => ['keepLeft']],
  [/^regulatory--no-entry/, () => ['noEntry']], [/^warning--/, () => ['warning']],
  [/^(information--general-directions|object--traffic-sign--direction-front|information--highway-interchange)/, () => ['direction']],
  [/^object--bench$/, () => ['bench']], [/^object--bike-rack$/, () => ['bikeRack']], [/^object--traffic-light/, () => ['trafficLight']],
  [/^object--mailbox$/, () => ['mailbox']], [/^object--fire-hydrant$/, () => ['hydrant']], [/^object--junction-box$/, () => ['cabinet']],
  [/^marking--discrete--crosswalk-zebra$/, () => ['zebra']], [/^marking--discrete--stop-line$/, () => ['stopLine']],
];
const near = (x, z) => { let best = null; for (const s of STREETS) for (let i = 1; i < s.pts.length; i++) { const [a, b] = [s.pts[i - 1], s.pts[i]], dx = b[0] - a[0], dz = b[1] - a[1], l = Math.hypot(dx, dz) || 1, t = Math.max(0, Math.min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / (l * l))), px = a[0] + t * dx, pz = a[1] + t * dz, d = Math.hypot(x - px, z - pz);
  if (!best || d < best.d) best = { d, px, pz, ux: dx / l, uz: dz / l, w: s.width || 7 }; } return best; };
const out = [];
for (const line of fs.readFileSync(process.argv[2], 'utf8').trim().split('\n')) {
  const f = JSON.parse(line), rule = KEEP.find(([re]) => re.test(f.object_value)); if (!rule) continue;
  const [type, value] = rule[1](f.object_value.match(rule[0]));
  const [lng, lat] = f.geometry.coordinates, [x, z] = geoToWorld(lat, lng);
  if (x < REGION.x0 || x > REGION.x1 || z < REGION.z0 || z > REGION.z1) continue;
  if (type === 'giveway' && NARROMINE_FURNITURE.giveway.some(([gx, gz]) => Math.hypot(gx - x, gz - z) < 12)) continue;
  const n = near(x, z); if (!n || n.d > 30) continue;
  // Road direction at the object; for signs, which way traffic sees them (keep-left: a sign on the left of
  // travel direction u faces back along -u).
  const left = (x - n.px) * n.uz - (z - n.pz) * n.ux > 0;     // left of travel along +u (x east, z south)
  out.push({ type, value: value ?? null, x: +x.toFixed(1), z: +z.toFixed(1), ux: +n.ux.toFixed(3), uz: +n.uz.toFixed(3), facing: left ? -1 : 1, roadW: n.w, cx: +n.px.toFixed(1), cz: +n.pz.toFixed(1), seen: f.last_seen_at?.slice(0, 10) || null, id: f.id });
}
fs.writeFileSync('src/world/narromine-mapillary-data.js', '// Generated by tools/narromine-mapillary-features.mjs — do not edit.\n' +
  '// Objects detected by Mapillary (map_features API) in CC BY-SA 4.0 street-level photos of Narromine.\n' +
  'export const NARROMINE_MAPILLARY_OBJECTS = ' + JSON.stringify(out) + ';\n');
const c = {}; for (const o of out) c[o.type] = (c[o.type] || 0) + 1; console.log(out.length, c);

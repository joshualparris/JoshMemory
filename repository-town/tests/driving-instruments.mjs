import assert from 'node:assert/strict';
import {FUEL_CAPACITY_L,updateCoolantTemperature,vehicleTelemetry} from '../src/world/driving-instruments.js';
assert.equal(FUEL_CAPACITY_L,30,'gauge uses same capacity as actual vehicle refuelling');
assert.equal(vehicleTelemetry(null),null,'no fake car when the player is walking');
const first=vehicleTelemetry({registration:'RT-101',model:'sedan',speed:10,fuel:15,odometer:64000.42,condition:84,coolantTemp:90});
assert.equal(first.speedKmh,36,'real m/s must be converted to km/h');
assert.equal(first.fuelLitres,15);
assert.equal(first.fuelPercent,50);
assert.equal(first.odometerKm,64000.4);
assert.equal(first.direction,'D');
assert.equal(first.coolantC,90);
assert.equal(first.lowFuel,false);
assert.equal(first.approximateRangeKm,50,'range grounded in current fuel burn');
const reverse=vehicleTelemetry({speed:-4,fuel:2,odometer:500,condition:80,coolantTemp:112});
assert.equal(reverse.speedKmh,14);
assert.equal(reverse.direction,'R');
assert.equal(reverse.lowFuel,true);
assert.equal(reverse.hotEngine,true);
const empty=vehicleTelemetry({speed:0,fuel:-3,coolantTemp:NaN,odometer:NaN});
assert.equal(empty.fuelLitres,0);
assert.equal(empty.odometerKm,0);
assert.equal(empty.coolantC,22);
let cold=22;
for(let n=0;n<3600;n++)cold=updateCoolantTemperature(cold,.15,10,85);
assert(cold>88&&cold<110,'engine must warm gradually into simulated operating range: '+cold);
assert(updateCoolantTemperature(22,.15,0,100)>22,'stationary engine still warms while idling');
assert(updateCoolantTemperature(95,.15,2,100)<95,'coolant regulates towards target rather than increasing without limit');
assert(updateCoolantTemperature(90,-1,0,100)===90,'invalid negative timestep cannot change temperature');
console.log('PASS: km/h, realistic fuel capacity and derived range, signed gear, odometer, warning flags and stable simulated engine temperature');

import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PLACE_DEFS } from '../src/world/life.js';
import {houseAddress,placeAddress,parseTownAddress,auditTownSlots} from '../src/world/addresses.js';
const inventory=JSON.parse(fs.readFileSync(new URL('../../docs/repository-town.json',import.meta.url),'utf8'));
const homes=inventory.projects.map(({coordinate,repo})=>({coordinate,name:repo.split('/').at(-1)}));
const a=auditTownSlots(homes,PLACE_DEFS);
const by=new Map(a.slots.map(s=>[s.address,s]));
assert.equal(homes.length,188);
assert.equal(a.slots.length,26*11*2);
assert.equal(a.counts.houses,188);
assert.equal(a.counts.sites,PLACE_DEFS.length);
assert.equal(a.counts.sites,46);
assert.equal(a.counts.railway,26);
assert.equal(new Set(a.slots.map(s=>s.address)).size,a.slots.length);
assert.deepEqual(parseTownAddress('z7'),{address:'Z7-S',col:'Z',row:7,side:'S',legacy:true});
assert.equal(parseTownAddress('z9 north')?.address,undefined);
assert.equal(parseTownAddress('z9-n')?.address,'Z9-N');
assert.equal(houseAddress('Z7'),'Z7-S');
assert.equal(by.get('Z7-S').kind,'house');
assert.match(by.get('Z7-S').name,/UpskillApp/);
assert.equal(by.get('Z7-N').kind,'not-surveyed');
assert.equal(by.get('Z8-N').kind,'railway');
assert.equal(by.get('Z8-S').name,'Farmhouse');
assert.equal(by.get('Z9-N').name,'Macquarie Locksmith & Keys');
assert.equal(by.get('Z9-S').kind,'unbuilt-not-surveyed');
assert.equal(by.get('B9-S').kind,'farm-field');
assert.equal(by.get('Y9-S').kind,'farm-field');
assert.equal(by.get('A10-N').kind,'planning-only');
assert.equal(by.get('Z11-S').kind,'planning-only');
assert.equal(placeAddress({col:'Z',side:'south'}),'Z9-N');
assert.equal(placeAddress({col:'Z'}),'Z8-S');
for(const p of inventory.projects)assert.equal(by.get(houseAddress(p.coordinate)).kind,'house');
for(const p of PLACE_DEFS)assert.equal(by.get(placeAddress(p)).name,p.name);
for(const c of 'GHIJKLMNOPQRSTUVWXYZ')assert.equal(by.get(c+'8-S').kind,'site');
console.log('Directional plot audit passed: '+a.counts.houses+' houses, '+a.counts.sites+' sites, '+a.counts.railway+' rail-corridor references, '+a.slots.length+' planning slots.');

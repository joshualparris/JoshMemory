import assert from 'node:assert/strict';
import * as THREE from 'three';
import { publicHeritageHouse, HERITAGE_COORDINATES, HERITAGE_LABELS, HERITAGE_GUIDES } from '../tools/heritage-houses.mjs';
import { PROPS } from '../src/world/props.js';
import { STYLES, FEATURE_NAMES, buildExterior } from '../src/world/exterior.js';
import { buildInterior } from '../src/world/interior.js';
import { Builder } from '../src/world/builder.js';
import { residentName } from '../src/ui/resident-identity.js';
const expected = {A3:'Elizabeth Farm', N3:'Monticello', T2:'Vaucluse House', I7:'Fallingwater'};
assert.deepEqual(Object.keys(expected).sort(), HERITAGE_COORDINATES.sort());
for (const [coordinate,name] of Object.entries(expected)) {
 const source={coordinate,street:'Demo Street',repo:'secret/old-repo',name:'Private Source',int:{rooms:[]},links:[{url:'https://github.com/secret/old-repo'}]};
 const h=publicHeritageHouse(source);
 assert.equal(h.name,name);
 assert.equal(h.repo,null);
 assert.equal(h.heritage,true);
 assert.equal(h.street,source.street);
 assert.equal(residentName(coordinate),HERITAGE_GUIDES[coordinate]);
 assert.ok(h.summary.length>=60);
 assert.ok(STYLES[h.ext.style]);
 assert.ok(h.ext.features.every(f=>FEATURE_NAMES.includes(f)));
 assert.ok(h.int.rooms.length>=4);
 assert.equal(h.links.length,2);
 assert.ok(h.links.every(link=>link.url.startsWith('https://')&&!link.url.includes('github.com')));
 const text=JSON.stringify(h);
 assert.ok(!text.includes('secret/old-repo')&&!text.includes('Private Source'));
 const acts=h.int.rooms.flatMap(r=>r.props.map(p=>p[2]).filter(Boolean));
 assert.ok(acts.some(a=>a.do==='npc'&&a.name===HERITAGE_GUIDES[coordinate]));
 assert.ok(acts.some(a=>a.do==='link'));
 for(const r of h.int.rooms)for(const [type] of r.props)assert.ok(PROPS[type],coordinate+' '+type);
 const b=new Builder();const fp=buildExterior(b,h.ext,h.ext);
 assert.ok(fp.w<=17&&fp.d<=14,coordinate+' lot footprint');
 const inside=buildInterior(h,()=>new THREE.Object3D());
 assert.ok(inside.rooms.length>=4,coordinate+' walkable interior');
 console.log(coordinate,name,inside.rooms.length,'rooms, footprint',fp.w,fp.d);
}
const memorial={coordinate:'C2',name:'Paul-Roe-Private-Archive',memorial:true,links:[{url:'https://example.com'}]};
assert.equal(publicHeritageHouse(memorial),memorial,'C2 memorial must remain unchanged');
console.log('Four heritage houses verified; C2 preserved.');

// The complete soybean crop -> factory -> refrigerated freight -> real café stock.
import assert from 'node:assert/strict';
import * as THREE from 'three';
import {TownLife} from '../src/world/life.js';
import {soyAction,soyReport,soyHourly,soyState} from '../src/world/soy-chain.js';
import {CAFE_MENU,cafeAvailable} from '../src/world/cafe-menu.js';
import {orderRecipe} from '../src/world/work-recipes.js';
import {buildCivicInterior} from '../src/world/shop-interior.js';
import {routeVisitor} from '../src/world/shop-visitors.js';
const homes=[];
for(let r=0;r<7;r++)for(let c=0;c<26;c+=2)homes.push({coordinate:String.fromCharCode(65+c)+(r+1),name:'House',door:{x:(c-12.5)*26,z:r*46-157}});
const fresh=()=>new TownLife({homes,minute:8*60,seed:20261021});
const t=fresh(),s=soyState(t),farm=t.place('soyfarm'),plant=t.place('soyplant'),cafe=t.place('cafe');
assert(farm&&plant,'new independent buildings exist and have real lots');
assert(t.villagers.some(v=>v.work==='soyfarm')&&t.villagers.some(v=>v.work==='soyplant'),'new real scheduled NPC workers');
assert.equal(cafe.stock.soymilk,0,'no magically available soy drink on a fresh save');
assert(!t.soyAction('soyplant','clean').ok,'unemployed visitor cannot run the processing line');
assert(!soyAction(t,'soyplant','clean',true).ok,'no production from empty inputs');
assert.equal(farm.out.soybeans,12,'finite carryover from last crop');
assert(soyAction(t,'soyfarm','sow',true).ok);
assert.equal(farm.out.soybeans,10,'sowing consumes real seed');
assert(!soyAction(t,'soyfarm','sow',true).ok,'double sow prevented');
assert(soyAction(t,'soyfarm','irrigate',true).ok);
assert(!soyAction(t,'soyfarm','irrigate',true).ok,'one recorded watering per day');
assert(soyAction(t,'soyfarm','inspect',true).ok);
assert(!soyAction(t,'soyfarm','harvest',true).ok,'immature soy never harvestable');
t.day+=7;t.minute=14*60;
const prior=farm.out.soybeans;
assert(soyAction(t,'soyfarm','harvest',true).ok);
assert(farm.out.soybeans>prior,'mature, inspected soybean crop produces finite real beans');
const tr=t.trucks[0];
tr.job={from:'soyfarm',to:'soyplant',good:'soybeans',n:6};tr.leg='pickup';
t.truckArrived(tr);assert.equal(tr.load.n,6);assert.equal(farm.out.soybeans,prior+(farm.out.soybeans-prior));
tr.leg='deliver';t.truckArrived(tr);
assert.equal(plant.stock.soybeans,6,'actual cargo delivered from farm to processing plant');
assert(soyAction(t,'soyplant','clean',true).ok);
assert.equal(plant.stock.soybeans,4);
assert(!soyAction(t,'soyplant','pack',true).ok,'raw beans cannot bypass heat cycle');
assert(soyAction(t,'soyplant','soak',true).ok);
assert(!soyAction(t,'soyplant','grind',true).ok,'soaking time enforced');
t.minute+=121;
assert(soyAction(t,'soyplant','grind',true).ok);
assert(soyAction(t,'soyplant','filter',true).ok);
assert(soyAction(t,'soyplant','heat',true).ok);
assert(!soyAction(t,'soyplant','pack',true).ok,'no unheated packaged beverage');
t.minute+=31;
assert(soyAction(t,'soyplant','pack',true).ok);
assert.equal(plant.out.soymilk,6);
assert.equal(s.lots.length,1);assert.equal(s.lots[0].allergen,'SOY');
tr.job={from:'soyplant',to:'cafe',good:'soymilk',n:6};tr.leg='pickup';
t.truckArrived(tr);assert.equal(tr.load.soyLots[0].id,s.lots[0]?.id||tr.load.soyLots[0].id);
assert.equal(plant.out.soymilk,0,'no duplicated stock on truck');
tr.leg='deliver';t.truckArrived(tr);
assert.equal(cafe.stock.soymilk,6,'café can only sell what was manufactured and shipped');
assert.equal(s.cafeLots.reduce((n,l)=>n+l.n,0),6,'shop preserves lot traceability');
const drink=CAFE_MENU.find(x=>x.id==='soy-latte');assert(drink&&cafeAvailable(cafe,drink));
const recipe=orderRecipe({item:'latte',milk:'soy',diet:'vegan'});
assert.deepEqual(recipe.ingredients,{coffee:1,soymilk:1},'the drink uses soy, not dairy or oat supply');
assert(orderRecipe({item:'soy-latte',milk:'soy'}).ingredients.soymilk===1);
assert(!orderRecipe({item:'soy-latte',milk:'soy'}).ingredients.milk,'no hidden cow milk');
const save=JSON.parse(JSON.stringify(t.snapshot())),reloaded=fresh();
assert(reloaded.restore(save));
assert.equal(reloaded.soyReport().cafe,6);
assert.equal(reloaded.soyReport().cafeLots[0].id,s.cafeLots[0].id,'batch provenance survives a reload');
reloaded.day+=4;reloaded.minute=10*60;
soyHourly(reloaded);
assert.equal(reloaded.place('cafe').stock.soymilk,0,'out-of-date chilled soy removed');
assert(reloaded.soyReport().waste>=6,'expired drinks logged as waste');
for(const site of [farm,plant]){
 const built=buildCivicInterior(site,()=>new THREE.Sprite(new THREE.SpriteMaterial()),t);
 const controls=built.interactables.filter(x=>x.act.do==='soy-action');
 assert(controls.length>3,site.id+' needs multiple REAL stage-specific machines');
 for(const c of controls){
  assert(routeVisitor(built.spawn,c.pos,built.colliders,built.bounds,.3),site.id+': unreachable '+c.key);
 }
 built.group.traverse(o=>{o.geometry?.dispose?.();o.material?.dispose?.();});
}
console.log('PASS: independent soy farm, real NPCs, crop water/seed/yield, timed food-safe plant stages, dated SOY-labelled stock, truck logistics, saleable café recipes, expired lot recall, save and 3D workstations');

import assert from 'node:assert/strict';
import * as THREE from 'three';
import { createTownActivity, activitySample, ACTIVITY_KEY } from '../src/world/town-activity.js';
import { createNarromineTraffic } from '../src/world/narromine-traffic.js';

const data = new Map(), storage = { getItem:k=>data.get(k)??null, setItem:(k,v)=>data.set(k,v) };
const activity = createTownActivity(storage);
assert.equal(activity.mode,'calm');
activity.set('standard');
assert.equal(createTownActivity(storage).mode,'standard');
assert.equal(data.get(ACTIVITY_KEY),'standard');
activity.set('invalid');
assert.equal(activity.mode,'calm');
const blocked = createTownActivity({getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}});
assert.equal(blocked.mode,'calm'); blocked.set('standard'); assert.equal(blocked.mode,'standard');
assert.equal(activitySample('car-1'),activitySample('car-1'));
const admitted = Array.from({length:1000},(_,i)=>activity.admits('car-'+i)).filter(Boolean).length;
assert(admitted>200 && admitted<300, `stable quarter sampling: ${admitted}`);
const residents = Array.from({length:120},(_,i)=>({id:i,x:(i%20)*1.5,z:Math.floor(i/20)*1.5,inside:false}));
const before = JSON.stringify(residents);
const selection = activity.outdoor(residents,{x:0,z:0});
assert(selection.size<=14);
for(const a of selection) for(const b of selection) if(a!==b) assert(Math.hypot(a.x-b.x,a.z-b.z)>=3.2);
assert.equal(JSON.stringify(residents),before,'presentation must not mutate simulation residents');
residents[0].engaged=true;
assert(activity.outdoor(residents,{x:0,z:0}).has(residents[0]),'conversation stays visible');
activity.set('standard'); assert.equal(activity.outdoor(residents,{x:0,z:0}),null);
activity.set('calm');
const calm = createNarromineTraffic(new THREE.Group(),{models:false,activity});
const standard = createNarromineTraffic(new THREE.Group(),{models:false});
assert.equal(calm.commute.population.people.length,standard.commute.population.people.length);
const school = calm.commute.population.workplaces.find(p=>p.name==='Narromine High School');
const eye = {x:school.x,z:school.z};
for(const traffic of [calm,standard]) traffic.update(.1,eye,630,2,2);
assert(calm.count<=24); assert(calm.parked.length<=40);
assert(calm.parked.length<standard.parked.length,'fewer real parked actors, not just hidden meshes');
assert(calm.parked.every(c=>activity.admits(c.carId)));
const ids = calm.cars.map(c=>c.id);
activity.set('standard'); calm.update(.01,eye,630,2,2);
assert(ids.every(id=>calm.cars.some(c=>c.id===id)),'toggle does not delete active nearby vehicles');

import assert from 'node:assert/strict';
import * as THREE from 'three';
import {TownLife} from '../src/world/life.js';
import {buildInterior} from '../src/world/interior.js';
import {buildHotelInterior,HOTEL_ROOM_COUNT} from '../src/world/hotel-interior.js';
import {buildCivicInterior} from '../src/world/shop-interior.js';
import {needsReport} from '../src/world/needs.js';
import {readFileSync} from 'node:fs';
const homes=[];
let originalBeds=0,addedBeds=0,coordinates=[];
for(let street=1;street<=8;street++){
  const briefs=JSON.parse(readFileSync(new URL('../briefs/row-'+street+'.json',import.meta.url)));
  for(let col=0;col<briefs.length;col++){
    const coordinate=String.fromCharCode(65+col)+street,spec=briefs[col].int;
    const authored=spec.rooms.some(r=>(r.props||[]).some(q=>(typeof q==='string'?q:q[0])==='bed'));
    if(authored)originalBeds++;
    const obj={coordinate,name:briefs[col].repo||coordinate,repo:briefs[col].repo,int:spec,
      door:{x:col*26,z:street*46}};
    homes.push(obj);
    const built=buildInterior(obj,()=>new THREE.Object3D());
    const beds=built.interactables.filter(i=>i.type==='bed'&&i.act?.do==='sleep');
    assert(beds.length>=1,coordinate+' must have at least one usable bed');
    assert(beds.every(b=>built.rooms[b.room]?.name),'bed belongs to a real accessible room');
    assert(built.placedProps.some(i=>i.type==='bed'),'real rendered bed exists');
    if(!authored)addedBeds++;
    coordinates.push(coordinate);
    built.group.traverse(o=>o.geometry?.dispose());
  }
}
assert.equal(homes.length,188);
assert.equal(originalBeds,4);
assert.equal(addedBeds,184);
const t=new TownLife({homes,minute:18*60,seed:20261020});
assert(t.place('hotel'),'I8 Railway Hotel exists as a civic site');
const hotel=buildCivicInterior(t.place('hotel'),()=>new THREE.Object3D());
assert.equal(HOTEL_ROOM_COUNT,4);
assert(hotel.rooms.length>=5,'reception and all four guest bedrooms are walkable');
const bedList=hotel.interactables.filter(i=>i.type==='bed'&&i.act?.do==='sleep');
assert.equal(bedList.length,4);
assert.deepEqual(bedList.map(b=>b.act.room),[1,2,3,4]);
assert(t.civic.player.hunger<60&&t.civic.player.fatigue<50);
t.tick(60);
assert(t.civic.player.hunger>34&&t.civic.player.fatigue>22);
assert(t.villagers.every(v=>Number.isFinite(v.fatigue)));
const v=t.villagers[0];
v.fatigue=75;v.step={kind:'sleep',at:'home',until:360};v.inside=true;v.path=[];
t.tick(50);
assert(v.fatigue<75,'village sleep must actually restore energy');
const me=t.civic.player;
me.bag.bread=1;me.hunger=84;
assert.match(t.eatItem('bread'),/Hunger/);
assert(me.hunger<84);
assert.equal(me.bag.bread,0);
assert.match(t.eatItem('bread'),/do not have/);
assert.match(t.sleepHotel(1),/book a hotel room/);
me.wallet=10;
assert.match(t.bookHotel(),/costs/,'no free booking when poor');
me.wallet=75;
const initialCash=me.wallet;
assert.match(t.bookHotel(),/Room \d booked/);
assert.equal(me.wallet,initialCash-24);
assert.equal(t.place('hotel').bookings.length,1);
assert.match(t.bookHotel(),/already have/);
const booking=me.hotelBooking;
assert.match(t.sleepHotel((booking.room%4)+1),/key is for/);
const snap=JSON.parse(JSON.stringify(t.snapshot()));
const restored=new TownLife({homes,minute:7*60,seed:20261020});
restored.restore(snap);
assert.equal(restored.civic.player.hotelBooking.room,booking.room);
assert.equal(restored.place('hotel').bookings.length,1);
assert.equal(restored.villagers[0].fatigue,v.fatigue);
const before=restored.day,spent=restored.civic.player.wallet+restored.civic.player.bank;
assert.match(restored.sleepHotel(booking.room),/slept at the hotel/);
assert(restored.civic.player.fatigue<35,'8 hours sleep restores player');
// Sleeping runs the clock into a new day, so the visitor's morning rent and power come out, and nothing else.
const billed=restored.civic.finance.visitorPaid;
assert.equal(restored.civic.player.wallet+restored.civic.player.bank+billed,spent,'sleep does not charge twice (only the daily household bills come out)');
assert.equal(restored.civic.player.hotelBooking,null);
assert(restored.day>=before);
assert.equal(restored.needsReport().rooms,4);
assert.equal(restored.time(),'06:00','overnight rest must finish at 06:00, not stop after eight hours');
// Regression: paid room 1 is usable at 14:00. Napping reduces fatigue,
// advances town time, and does not surrender the room key prematurely.
const afternoon=new TownLife({homes,minute:14*60,seed:20261020});
afternoon.civic.player.wallet=80;
afternoon.civic.player.fatigue=92;
assert.match(afternoon.bookHotel(),/Room \d booked/);
const room=afternoon.civic.player.hotelBooking.room;
assert.match(afternoon.sleepHotel((room%4)+1),/key is for/,'only the booked guest bed is usable');
const dayBefore=afternoon.day;
const message=afternoon.sleepHotel(room);
assert.match(message,/two-hour nap at the hotel/);
assert.equal(afternoon.time(),'16:00','afternoon rest advances two hours');
assert.equal(afternoon.day,dayBefore);
assert(afternoon.civic.player.fatigue<=55,'92% fatigue must improve substantially after a nap');
assert.equal(afternoon.civic.player.hotelBooking.room,room,'nap should preserve the paid room key');
console.log('PASS: 188 homes with usable beds ('+addedBeds+' added), 4 hotel guest beds, persisted bookings, paid rest, hunger/food consumption, villager fatigue and sleep recovery');

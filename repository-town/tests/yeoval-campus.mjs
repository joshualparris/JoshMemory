import assert from 'node:assert/strict';
import * as THREE from 'three';
import {YEOVAL_SITE,buildYeovalCampus,yeovalWorld} from '../src/world/yeoval-campus.js';
import {buildYeovalInterior} from '../src/world/yeoval-interior.js';

const near=(a,b,delta=.001)=>Math.abs(a-b)<delta;
const hasPoint=(all,x,z,r=.35)=>all.some(s=>x+r>s.x0&&x-r<s.x1&&z+r>s.z0&&z-r<s.z1);
const group=new THREE.Group(), colliders=[];
const campus=buildYeovalCampus(group,colliders);
assert.equal(campus.id,'yeoval-aged-care');
assert.ok(campus.wings.length>=3,'north and south wings linked');
assert.ok(campus.wings[0].w>campus.wings[2].w,'longer north frontage');
assert.ok(campus.entry.z<campus.z,'door faces northern land');
assert.ok(near(yeovalWorld(11,19).z,campus.entry.z) && near(yeovalWorld(11,19).x,campus.entry.x),'entry transform');
assert.ok(!hasPoint(colliders,campus.entry.x,campus.entry.z,0.2),'door passage does not block entrance');
assert.ok(colliders.some(c=>hasPoint([c],campus.entry.x+12,campus.entry.z+5)),'bedroom wing is solid');
assert.ok(group.children.includes(campus.mesh),'campus rendered outdoors');
const labels=[];
const i=buildYeovalInterior(label=>{labels.push(label);return new THREE.Object3D()});
assert.ok(i.rooms.length>=4,'distinct wings and linking passage');
assert.ok(i.interactables.length>=5,'public-reference exhibits');
assert.ok(i.placedProps.some(p=>p.type==='bed'),'resident furniture');
assert.ok(i.group.children.length>=5,'real visible room geometry');
assert.ok(!hasPoint(i.colliders,i.spawn.x,i.spawn.z,.35),'spawn is free');
assert.ok(!hasPoint(i.colliders,0,8,.35),'north hallway clear');
assert.ok(!hasPoint(i.colliders,0,-7,.35),'connecting passage clear');
assert.ok(!hasPoint(i.colliders,0,-18.4,.35),'southern hallway clear');
assert.ok(!hasPoint(i.colliders,0,16.95,.35),'interior exit usable');
assert.ok(i.exitZone.z0>i.spawn.z,'exit at north entrance');
assert.ok(i.group.children.filter(x=>x.isLight).length>0,'corridor is lit');
console.log('Yeoval campus static footprint, circulation, collision and interior checks passed.');

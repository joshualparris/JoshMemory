import assert from 'node:assert/strict';
import {pickInteriorInteraction as pick} from '../src/engine/interaction-picker.js';
const at={x:-1,z:0},forward={x:1,z:0};
const wall={x0:-.1,x1:.1,y0:0,y1:3,z0:-3,z1:3};
const through={key:'behind-wall',pos:{x:.4,z:0},act:{do:'info'}};
const own={key:'same-room',pos:{x:-.5,z:0},act:{do:'info'}};
const room={sight:[wall],interactables:[through,own]};
assert.equal(pick(room,at,forward)?.key,own.key,'a closer hidden exhibit must not steal the prompt');
assert.equal(pick({...room,interactables:[through]},at,forward),null,'cannot use through a solid wall');
assert.equal(pick({...room,sight:[]},at,forward)?.key,own.key,'nearest visible exhibit keeps its prior priority');
const door={userData:{open:0}};
assert.equal(pick({...room,sight:[{...wall,door}],interactables:[through]},at,forward),null,'closed door blocks Use');
door.userData.open=1;
assert.equal(pick({...room,sight:[{...wall,door}],interactables:[through]},at,forward)?.key,through.key,'open doorway permits Use');
const seat={key:'chair',pos:through.pos,label:'Chair'};
assert.equal(pick({sight:[wall],seats:[seat]},at,forward),null,'cannot sit through a wall');
assert.equal(pick({sight:[wall],furniture:[through]},at,forward),null,'passive furniture obeys walls too');
assert.equal(pick({sight:[],seats:[seat]},at,forward)?.act.do,'sit','clear seats remain usable');
assert.equal(pick({sight:[],seats:[{...seat,occupiedBy:'Guest'}]},at,forward),null,'occupied seat stays unavailable');
const mounted={...through,pos:{x:-.1,z:0}};
assert.equal(pick({sight:[wall],interactables:[mounted]},at,forward)?.key,mounted.key,'mounting wall does not hide its own inner-face exhibit');
console.log('PASS: walls and closed doors block exhibits, seats and furniture without stealing visible prompts');

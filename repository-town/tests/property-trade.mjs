import assert from 'node:assert/strict';
import * as THREE from 'three';
import { TownLife } from '../src/world/life.js';
import { propertyKey,depositFor,PROPERTY_YEAR } from '../src/world/property.js';
import { buildCivicInterior } from '../src/world/shop-interior.js';
const homes=Array.from({length:188},(_,i)=>({coordinate:String.fromCharCode(65+i%26)+(1+Math.floor(i/26)),name:'House '+i,door:{x:(i%26-12.5)*26,z:(Math.floor(i/26)-3.5)*46+7}}));
const make=()=>new TownLife({homes});
let town=make(),report=town.propertyReport(),state=town.civic.property;
assert.equal(Object.keys(state.parcels).filter(k=>k.startsWith('H:')).length,188);
assert.equal(report.total,188+town.places.size);
assert(report.public>=10&&report.forSale.length>=20);
for(const v of town.villagers){
  const p=state.parcels[propertyKey('house',v.home.coordinate)];
  assert.equal(p.tenant,v.name);
  if(v.household.tenure!=='rent')assert.equal(p.owner,'resident:'+v.name);
}
const lab=()=>new THREE.Sprite(new THREE.SpriteMaterial());
for(const [id,col] of [['realestate','S'],['dealership','T'],['mechanic','U']]){
  const site=town.place(id);
  assert.equal(site.col,col);assert.equal(site.side,'south');
  const room=buildCivicInterior(site,lab,town);
  assert.equal(room.interactables.length,3,id+' has 3 operational exhibits');
  assert(room.colliders.length>=7&&room.windows.length>=4,id+' has a walkable shell');
  room.group.traverse(o=>{o.geometry?.dispose?.();o.material?.dispose?.();});
}
const listing=report.forSale.find(p=>!p.tenant&&p.kind==='house');assert(listing);
const deposit=depositFor(listing),beforeReserve=state.reserve,oldOwner=listing.owner;
assert.match(town.buyProperty(listing.id),/need|enough/);
town.civic.player.bank=deposit+100;
assert.match(town.buyProperty(listing.id),/Settlement complete/);
assert.equal(listing.owner,'visitor');
assert(state.reserve<beforeReserve&&state.accounts[oldOwner]>0);
assert.equal(state.liens[listing.id].balance,listing.value*.8);
assert.match(town.listProperty(listing.id),/Listed/);
assert.match(town.sellProperty(listing.id),/Sale settled/);
assert.equal(listing.owner,'Town Property Cooperative');
assert(!state.liens[listing.id]);
const home=report.forSale.find(p=>!p.tenant&&p.id!==listing.id);
town.civic.player.bank=5000;
assert.match(town.leaseProperty(home.id),/Lease signed/);
assert.equal(state.bond,home.rent*PROPERTY_YEAR);
assert.match(town.endLease(),/bond refunded/i);
assert.equal(home.tenant,null);
assert.match(town.buyProperty('B:fire'),/not currently available/);
const investment=town.propertyReport().forSale.find(p=>p.tenant&&!p.protected);
assert(investment,'a tenant-occupied investment listing');
town.civic.player.bank=8000;
assert.match(town.buyProperty(investment.id),/Settlement complete/);
assert(investment.tenant&&investment.owner==='visitor');
const tenant=town.villagers.find(v=>v.name===investment.tenant);
tenant.wallet=500;town.day=2;town.newDay();
assert.equal(investment.tenant,tenant.name);
assert(town.civic.player.wallet>=0&&town.civic.player.bank>=0);
const motor=town.motorReport(),used=motor.stock[0];
town.civic.player.bank=15000;
assert.match(town.buyVehicle(used.stockId),/registered in your name/);
assert.equal(motor.stock.length,4);
const vehicle=motor.owned[0];
assert.match(town.serviceVehicle(vehicle.registration),/serviced/);
assert(motor.parts<20);
assert.match(town.renewRegistration(vehicle.registration),/renewed/);
assert.match(town.sellVehicle(vehicle.registration),/Dealer settled/);
assert.equal(motor.owned.length,0);
const snap=town.snapshot(),other=make();
assert(other.restore(snap),'land titles and vehicle ownership survive save/restore');
assert.equal(other.civic.property.parcels[investment.id].owner,'visitor');
assert.equal(other.civic.motor.stock.length,motor.stock.length);
console.log('PASS: property titles, buyers, mortgages, tenants, agencies, dealers, mechanics and persistence');

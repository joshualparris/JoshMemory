import assert from 'node:assert/strict';
import * as THREE from 'three';
import { townDate } from '../src/world/town-calendar.js';
import { SOLAR_SITE, nswUtcOffsetHours, solarPosition, solarDaylight, solarWarmth, solarRiseSet } from '../src/world/solar-position.js';
import { SHADOW_STORAGE_KEY, SHADOW_LEVELS, loadShadowChoice, configureOutdoorShadows, createSunShadows } from '../src/world/sun-shadows.js';

const summer = {year:2026,month:12,day:21},winter={year:2027,month:6,day:21};
const sp=(date,minute)=>solarPosition(date,minute);
const sunSummer=sp(summer,13*60),sunWinter=sp(winter,12*60);
assert(townDate(57).iso==='2026-12-21','town summer solstice is day 57');
assert(townDate(239).iso==='2027-06-21','town winter solstice is day 239');
assert.equal(nswUtcOffsetHours(summer),11,'summer +11 AEDT');
assert.equal(nswUtcOffsetHours(winter),10,'winter +10 AEST');
assert.equal(nswUtcOffsetHours({year:2026,month:10,day:4},119),10,'DST starts at 2am Oct first Sunday');
assert.equal(nswUtcOffsetHours({year:2026,month:10,day:4},120),11);
assert.equal(nswUtcOffsetHours({year:2026,month:4,day:5},179),11,'DST ends at 3am Apr first Sunday');
assert.equal(nswUtcOffsetHours({year:2026,month:4,day:5},180),10);
assert(sunSummer.elevation>75&&sunSummer.elevation<85,'summer noon elevation '+sunSummer.elevation);
assert(sunWinter.elevation>31&&sunWinter.elevation<38,'winter noon elevation '+sunWinter.elevation);
assert(sunSummer.azimuth<30||sunSummer.azimuth>330,'summer midday sun is NORTH');
assert(sunWinter.azimuth<30||sunWinter.azimuth>330,'winter midday sun is NORTH');
assert(sunSummer.direction.z<-.08&&sunWinter.direction.z<-.52,'world -Z is north; summer midday light points mainly downward');
for(const [d,h,azRange] of [[summer,6,[95,135]],[summer,19,[240,290]],[winter,8,[40,95]],[winter,16,[260,325]]]){
 const p=sp(d,h*60);
 assert(p.azimuth>azRange[0]&&p.azimuth<azRange[1],
   JSON.stringify(d)+' '+h+':00 azimuth '+p.azimuth+' degrees');
}
const summerTimes=solarRiseSet(summer),winterTimes=solarRiseSet(winter);
assert(summerTimes.sunrise>5*60&&summerTimes.sunrise<7*60,'summer sunrise early');
assert(summerTimes.sunset>19*60&&summerTimes.sunset<21*60,'summer sunset late');
assert(winterTimes.sunrise>6*60&&winterTimes.sunrise<8*60,'winter sunrise later');
assert(winterTimes.sunset>16*60&&winterTimes.sunset<18*60,'winter sunset early');
assert(summerTimes.sunset-summerTimes.sunrise>14*60,'summer day over 14h');
assert(winterTimes.sunset-winterTimes.sunrise<11*60,'winter day under 11h');
assert.equal(solarDaylight(-8),0);assert.equal(solarDaylight(45),1);
assert(solarWarmth(6)>solarWarmth(40),'low sun warmer than midday');
const shadowLength=(height,el)=>height/Math.tan(el*Math.PI/180);
assert(shadowLength(7,sunSummer.elevation)<1.8,'short summer shadow');
assert(shadowLength(7,sunWinter.elevation)>9,'long winter shadow');

const storageValues=new Map(),storage={getItem:k=>storageValues.get(k)??null,setItem:(k,v)=>storageValues.set(k,v)};
assert.equal(loadShadowChoice(storage),'auto');
storageValues.set(SHADOW_STORAGE_KEY,'__garbage');
assert.equal(loadShadowChoice(storage),'auto','invalid saved setting safe');
storageValues.clear();
const root=new THREE.Scene(),light=new THREE.DirectionalLight(),renderer={shadowMap:{enabled:false,autoUpdate:true,type:null,needsUpdate:false}};
root.add(light);
const controller=createSunShadows({renderer,scene:root,sun:light,storage,coarse:false});
assert.equal(controller.state.level,'medium','desktop auto medium');
assert.equal(controller.state.pixels,1024);
assert(renderer.shadowMap.enabled&&!renderer.shadowMap.autoUpdate,'cached PCF shadow passes');
assert.equal(light.shadow.camera.left,-105);
controller.update({direction:sunWinter.direction,elevation:sunWinter.elevation,eye:{x:-3130,z:251},dt:.4});
assert(light.castShadow&&renderer.shadowMap.needsUpdate,'shadow pass in Narromine');
assert(Math.abs(light.target.position.x+3130)<.01&&Math.abs(light.target.position.z-251)<.01,'shadow target follows player');
const direction=new THREE.Vector3().subVectors(light.position,light.target.position).normalize();
assert(Math.abs(direction.z-sunWinter.direction.z)<1e-6,'shadow light follows geographic north');
controller.update({direction:sunWinter.direction,elevation:-12,eye:{x:-3130,z:251}});
assert(!light.castShadow,'no shadow map at night');
controller.setChoice('high');assert.equal(controller.state.pixels,2048);
controller.setChoice('off');assert(!renderer.shadowMap.enabled,'user can disable shadows');
assert.equal(storageValues.get(SHADOW_STORAGE_KEY),'off','choice saved');
controller.setChoice('low');assert.equal(controller.state.pixels,512);
const mobileRenderer={shadowMap:{enabled:false,autoUpdate:true,needsUpdate:false}};
const mobileLight=new THREE.DirectionalLight();root.add(mobileLight);
const mobile=createSunShadows({renderer:mobileRenderer,scene:root,sun:mobileLight,coarse:true});
assert.equal(mobile.state.level,'low','phone auto 512px');
for(let i=0;i<35;i++)mobile.update({direction:sunWinter.direction,elevation:40,eye:{x:0,z:0},dt:.2,frameSeconds:.18});
assert.equal(mobile.state.level,'minimal','slow mobile auto-downgrades');
const box=()=>new THREE.Mesh(new THREE.BoxGeometry(5,5,5),new THREE.MeshLambertMaterial());
const testTown=new THREE.Group(),house=new THREE.Group();house.add(box());testTown.add(house);
const ground=box();
const town={group:testTown,ground,lots:new Map([['A1',{mesh:house}]]),doors:[],outskirts:{group:new THREE.Group()}};
const west=new THREE.Group(),narroot=new THREE.Group();narroot.add(west);
const raised=box(),flat=box();flat.geometry=new THREE.BoxGeometry(100,0.08,100);
west.add(raised,flat);
const nar={group:west,root:narroot};
const estate=new THREE.Group(),home=new THREE.Group();home.name='1 Wattle Street · Australia';home.add(box());estate.add(home);
const masterplan={group:estate};
const shopMesh=box(),life={places:new Map([['cafe',{id:'cafe'}]])};
const lifeMock={life,building:id=>id==='cafe'?[shopMesh]:[]};
const tally=configureOutdoorShadows(town,nar,masterplan,lifeMock);
assert(tally.casters>=4&&tally.receivers>=4,'original, estate, shop and Narromine casters');
assert(house.children[0].castShadow&&home.children[0].castShadow&&shopMesh.castShadow&&raised.castShadow);
assert(flat.receiveShadow&&!flat.castShadow,'ground receives but cannot cast');
assert(ground.receiveShadow);
console.log('PASS seasonal sun and shadows: NSW DST, sunrises, winter/summer, soft PCF, 195 new estate homes, mobile adaptation');
